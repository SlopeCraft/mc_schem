#include <cstdint>
#include <mc_schem.hpp>
#include <spanstream>
#include <sstream>
#include <vector>

#include "utils.hpp"

extern const std::vector<uint8_t> test_nbt_file;

int main(int, char**) {
  using namespace mc_schem;
  {
    auto empty = nbt_hashmap::create();
    [[maybe_unused]] auto len = empty->size();
    MC_SCHEM_CHECK(len == 0);
  }

  {
    [[maybe_unused]] auto nbt =
        nbt_hashmap::create_from_binary(test_nbt_file).value();
    [[maybe_unused]] auto vec = nbt->dump();
    MC_SCHEM_CHECK(vec.size() == test_nbt_file.size());
  }

  {
    std::ispanstream is{
        std::span{reinterpret_cast<const char*>(test_nbt_file.data()),
                  test_nbt_file.size()}};
    [[maybe_unused]] auto nbt =
        nbt_hashmap::create_from_binary_stream(is).value();

    std::ostringstream oss;
    nbt->dump_to_stream(oss).value();

    std::vector<uint8_t> vec;
    nbt->dump_to_vector(vec);
    MC_SCHEM_CHECK(vec.size() == test_nbt_file.size());
  }

  return 0;
}

